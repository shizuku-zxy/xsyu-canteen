def order_tags(tags):
    """标签按维度排序（品类→细分→特点→主料→口味→做法），去重保序。"""
    seen, out = set(), []
    for t in tags:
        if t and t not in seen:
            seen.add(t)
            out.append(t)
    return sorted(out, key=lambda t: (DIM_ORDER.index(TAG_DIM.get(t, "其他")),
                                      list(TAG_DIM).index(t) if t in TAG_DIM else 999))


def match_group(tag):
    """查询标签 → 同义标签组（组内任一命中即通过过滤）。"""
    return _GROUP.get(tag, [tag])


def surfaces_for_tags(tags):
    """标签组 → 直接命中用的同义叫法集合（菜名含任一词算同义命中）。"""
    out = set()
    for t in tags or ():
        out |= _SURFACES_OF_GROUP.get(t, set())
    return out


def tags_for_dish(name, category, existing_tags=(), shop=None):
    """离线标注：一道菜 → 完整标签列表（保留原有标签 + 预算 + 细分 + 主料 + 口味 + 做法）。

    规则（2026-11）：标签宁多勿少，但**不许乱加**——
      · 菜名扫描用最长命中优先、互不重叠，防「稀饭→饭」「面筋→面」这类误伤；
      · 主料/口味/做法正则各自带 avoid，命中才加；
      · 肉/海鲜命中时补「荤菜」，并撤掉原数据里矛盾的「素食/素菜」；
      · 原有标签保留（人工维护过的），只补不改。
    """
    name = name or ""
    tags = set(t for t in (existing_tags or ()) if t)
    cat = (category or "").strip()

    # 1) 品类兜底（按菜名模式；见 CATEGORY_RULES 注释）
    _rule = CATEGORY_RULES.get(cat)
    if _rule and re.search(_rule[0], name):
        tags.update(_rule[1])

    # 2) 细分食物家族（最长优先、互不重叠）
    remaining = name
    family_tags = set()
    for fam in _FAM:
        if fam["avoid_re"] and fam["avoid_re"].search(name):
            continue
        hit = None
        for term in fam["terms_sorted"]:
            if term in remaining:
                hit = term
                break
        if hit:
            family_tags.update(fam["tags"])
            remaining = remaining.replace(hit, "\u0000")
    tags |= family_tags

    # 3) 主料 / 口味 / 做法（菜名正则；与原标签合并）
    hit_materials = set()
    for tag, (pat, avoid) in _MATERIAL_RULES_C:
        if pat and pat.search(name) and not (avoid and avoid.search(name)):
            tags.add(tag)
            if tag in ("猪肉", "牛肉", "羊肉", "鸡肉", "鸭肉", "鱼虾"):
                hit_materials.add(tag)
    for tag, (pat, avoid) in _TASTE_RULES_C:
        if pat and pat.search(name) and not (avoid and avoid.search(name)):
            tags.add(tag)
    for tag, (pat, avoid) in _METHOD_RULES_C:
        if pat and pat.search(name) and not (avoid and avoid.search(name)):
            tags.add(tag)

    # 4) 荤 / 素 一致性（菜名里的「素」优先：素臊子干拌不能带猪肉）
    meat_tags = {"猪肉", "牛肉", "羊肉", "鸡肉", "鸭肉", "鱼虾"}
    veg_by_name = bool(re.search(r"素|全素|纯素|斋", name)) and not re.search(r"荤", name)
    if veg_by_name:
        tags -= meat_tags
        tags.add("素食")
        tags.discard("荤菜")
        tags.discard("素菜")
    elif "荤菜" in tags:
        # 老标签自相矛盾（如「生汆丸子汤」标了素食又标荤菜）：以荤菜为准
        tags.discard("素食")
        tags.discard("素菜")
    elif hit_materials or (tags & meat_tags):
        tags.add("荤菜")
        tags.discard("素食")
        tags.discard("素菜")

    # 5) 低卡：轻食类 / 沙拉
    if (category or "").strip() in ("轻食", "轻食粥品") or "轻食" in tags or "沙拉" in tags:
        tags.add("低卡")

    # 6) 早餐：原有标签保留；粥/豆浆/油条/包子/馒头/花卷/饼/蒸蛋 这类早点补早餐
    if not tags & {"早餐"}:
        if re.search(r"豆浆|油条|粥|稀饭|包子|馒头|花卷|茶叶蛋|煎饼|蒸饺|蒸包|鸡蛋灌饼|胡辣汤|豆腐脑|糖糕|菜盒", name) \
                and not re.search(r"午夜|夜宵", name):
            tags.add("早餐")

    # 7) 甜品 / 饮品兜底（category=甜品饮品 时按菜名区分）
    if (category or "").strip() == "甜品饮品":
        if DESSERT_WORDS.search(name) and "饮品" not in tags:
            tags.add("甜品")
        elif DRINK_WORDS.search(name) and "甜品" not in tags:
            tags.add("饮品")
        elif not (tags & {"甜品", "饮品"}):
            tags.add("甜品" if re.search(r"奶|花|果|茶|糖", name) and not DRINK_WORDS.search(name) else "饮品")

    # 8) 撤掉明显矛盾：粥不可能是米饭；粉条/米线不是米饭
    if tags & {"粥", "稀饭", "面", "粉", "馒头", "花卷", "饼", "包子", "饺子"}:
        if not re.search(r"米饭|盖饭|炒饭|拌饭|饭团|盖浇", name):
            tags.discard("米饭")
    return order_tags(tags)


def scan_query(text):
    """用户口语 → {tags, terms, keywords, leftover}。

    · tags     命中的规范标签组（父级/同义都在里面）
    · terms    主观命中词（用于 recommend 直接命中加权）
    · keywords 具体菜名/食材词（用于按菜名直接命中）
    · leftover 未被消费的剩余片段（交给上层做菜名关键词兜底）
    """
    s = text or ""
    orig = text or ""
    tags, terms, keywords, food_terms = [], [], [], []
    matched_kw_surfs = []

    def _add(seq, x):
        if x and x not in seq:
            seq.append(x)

    for surf in _QUERY_KEYS:
        if not surf or surf not in s:
            continue
        hit_tags, hit_kw, is_food = _QUERY_SURFACES[surf]
        for t in hit_tags:
            _add(tags, t)
        for k in hit_kw:
            _add(keywords, k)
        if hit_kw:
            matched_kw_surfs.append(surf)
        else:
            _add(terms, surf)
            if is_food:
                _add(food_terms, surf)
        s = s.replace(surf, "\u0000")
    # 2026-11：关键词命中时，把原句里包含它的**整段菜名**也当关键词（如「土豆丝」→
    # 土豆 + 丝；「番茄炒蛋」→ 番茄 + 炒蛋），这样直接命中优先能排到「土豆丝」而不是「土豆片烤肉」
    for surf in matched_kw_surfs:
        m = re.search(r"[\u4e00-\u9fa5]*" + re.escape(surf) + r"[\u4e00-\u9fa5]*", orig)
        if not m:
            continue
        token = clean_mood(m.group(0))
        if token and token != surf and len(token) <= 12:
            _add(keywords, token)
    leftover = s.replace("\u0000", "")
    return {"tags": tags, "terms": terms, "food_terms": food_terms,
            "keywords": keywords, "leftover": leftover}


def clean_mood(text):
    """去掉语气词/动词，留下可能的菜名片段。"""
    s = _MOOD_STRIP.sub(" ", text or "")
    s = re.sub(r"[\s，。、,;；！!？?～~…:：\"'“”‘’()（）【】\[\]]+", " ", s)
    return s.strip()


def leftover_keywords(leftover):
    """剩余片段 → 菜名关键词（只在像菜名时才返回，否则 []）。"""
    s = clean_mood(leftover)
    if not s:
        return []
    parts = [p for p in s.split(" ") if p]
    out = []
    for p in parts:
        if 1 < len(p) <= 10 and not re.fullmatch(r"[a-zA-Z0-9]+", p):
            out.append(p)
    return out


def apply_counter_tags(tags):
    """反义词：查询标签 → 需要额外排除的标签（不包含在本次要的标签里）。"""
    need = set(tags or ())
    out = []
    for t in tags or ():
        for c in COUNTER_TAGS.get(t, ()):
            if c not in need and c not in out:
                out.append(c)
    return out


def normalize_tag(tag):
    """口语/别名 → 规范标签（认不出原样返回）。"""
    t = (tag or "").strip()
    if not t:
        return ""
    if t in TAG_DIM:
        return t
    if t in EXTRA_SYNONYMS:
        return EXTRA_SYNONYMS[t]
    return t
